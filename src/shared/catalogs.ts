const catalogCodeSets = new WeakMap<readonly CatalogOption[], Set<string>>();

export function normalizeCatalogCode(value: unknown): string {
  return String(value ?? "").trim().toUpperCase();
}

export function findCatalogOption<T extends CatalogOption>(catalog: readonly T[], value: unknown): T | null {
  const code = normalizeCatalogCode(value);
  return catalog.find((option) => option.code === code) ?? null;
}

export function isCatalogCode(catalog: readonly CatalogOption[], value: unknown): boolean {
  let codeSet = catalogCodeSets.get(catalog);
  if (!codeSet) {
    codeSet = new Set(catalog.map((option) => option.code));
    catalogCodeSets.set(catalog, codeSet);
  }
  return codeSet.has(normalizeCatalogCode(value));
}

